"""uwu adapter runs vs the overnight runs, at matching steps: plots + tables.

    uv run --with matplotlib python experiments/core_rl/compare_uwu.py

Writes results/core_rl_uwu/tables.md and results/core_rl_uwu/plots/*.png.
"""

import json
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

CORE, UWU = Path("results/core_rl"), Path("results/core_rl_uwu")
OUT = UWU / "plots"
COLORS = {"uwu": "#7c3aed", "Aghyad": "#c2410c", "120b": "#1d4ed8", "20b": "#15803d"}
UNDER = {"uwu": (UWU / "C2u", UWU / "C2u"), "Aghyad": (CORE / "C2", CORE / "C1"),
         "120b": (CORE / "C4", CORE / "C3"), "20b": (CORE / "C6", CORE / "C5")}  # (run dir, step-0 eval dir)
S1 = {"uwu": UWU / "S1u", "Aghyad": CORE / "S1a", "120b": CORE / "S1b", "20b": CORE / "S1c"}


def load(p):
    return [json.loads(line) for line in open(p)] if p.exists() else []


def eval_curve(run, step0, task):
    steps = sorted(int(p.stem.removeprefix("eval_step")) for p in run.glob("eval_step*.jsonl"))
    curve = {}
    for s in sorted(set(steps) | {0}):
        rows = [r for r in load((step0 if s == 0 else run) / f"eval_step{s}.jsonl") if r.get("task") == task]
        if not rows:
            continue
        correct = [r for r in rows if r["true_score"]]
        curve[s] = {"true": sum(r["true_score"] for r in rows) / len(rows),
                    "compliance": sum(r["rule_ok"] for r in correct) / len(correct) if correct else float("nan"),
                    "trunc": sum(r["truncated"] for r in rows) / len(rows), "n": len(rows)}
    return curve


def train_compliance(run, task):
    by = defaultdict(list)
    for r in load(run / "rollouts.jsonl"):
        if r["task"] == task and r["true_score"]:
            by[r["step"]].append(r["rule_ok"])
    return {s: sum(v) / len(v) for s, v in sorted(by.items())}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["# uwu vs overnight runs: tables (generated by compare_uwu.py)\n"]
    # zebra compliance: training (per step) and held-out (per eval)
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))
    lines.append("## Zebra, underspecified: held-out eval (true / compliance of correct / truncation)\n")
    lines.append("| Model | Step | n | True | Compliance | Truncation |\n|---|---|---|---|---|---|")
    for name, (run, s0) in UNDER.items():
        tc = train_compliance(run, "zebra_puzzles")
        xs = [s for s in tc if s <= 20]
        axes[0].plot(xs, [tc[s] for s in xs], marker="o", ms=3, lw=2, color=COLORS[name], label=name)
        ec = eval_curve(run, s0, "zebra_puzzles")
        es = [s for s in ec if s <= 20]
        axes[1].plot(es, [ec[s]["compliance"] for s in es], marker="o", lw=2, color=COLORS[name], label=name)
        for s in es:
            lines.append(f"| {name} | {s} | {ec[s]['n']} | {ec[s]['true']:.2f} | {ec[s]['compliance']:.2f} | {ec[s]['trunc']:.2f} |")
    for ax, title in zip(axes, ("training rollouts (per step)", "held-out eval")):
        ax.axhline(0.5, color="#999", lw=1, ls=":")
        ax.set_title(f"Zebra lowercase rule, {title}")
        ax.set_xlabel("step")
        ax.set_ylim(-0.03, 1.03)
        ax.grid(alpha=0.3)
        ax.legend(fontsize=8)
    axes[0].set_ylabel("compliance")
    fig.tight_layout()
    fig.savefig(OUT / "zebra_compliance.png", dpi=130)
    plt.close(fig)

    lines.append("\n## Zebra: training step at which compliance first reaches 50%\n")
    lines.append("| Model | Step | Compliance, steps 0–15 |\n|---|---|---|")
    for name, (run, _) in UNDER.items():
        tc = train_compliance(run, "zebra_puzzles")
        first = next((s for s, v in tc.items() if v >= 0.5), None)
        lines.append(f"| {name} | {first} | " + " ".join(f"{tc[s]:.2f}" for s in list(tc)[:16]) + " |")

    # S1: true score and hardcoding, eval and training
    fig, axes = plt.subplots(1, 2, figsize=(12, 4))
    lines.append("\n## S1 normal coding: held-out eval\n")
    lines.append("| Model | Step | n | True | Hardcoding | True among non-hardcoding (n) |\n|---|---|---|---|---|---|")
    for name, run in S1.items():
        ev = {e["step"]: e for e in load(run / "evals.jsonl")}
        xs = sorted(ev)
        axes[0].plot(xs, [ev[x]["true_score"] for x in xs], marker="o", lw=2, color=COLORS[name], label=f"{name} true")
        axes[0].plot(xs, [ev[x].get("hardcode") for x in xs], marker="s", lw=1.5, ls=":", color=COLORS[name],
                     label=f"{name} hardcoding")
        ms = {m["step"]: m for m in load(run / "metrics.jsonl")}
        steps = sorted(ms)
        axes[1].plot(steps, [ms[s].get("hardcode") for s in steps], marker="o", ms=3, lw=2, color=COLORS[name], label=name)
        for x in xs:
            e = ev[x]
            tn = e.get("true_nonhardcode")
            lines.append(f"| {name} | {x} | {e['n']} | {e['true_score']:.2f} | {e.get('hardcode', 0):.2f} | "
                         f"{'—' if tn is None else f'{tn:.2f}'} ({e.get('n_nonhardcode')}) |")
    axes[0].set_title("S1 held-out: true score (solid) and hardcoding (dotted)")
    axes[1].set_title("S1 training rollouts: hardcoding rate")
    for ax in axes:
        ax.set_xlabel("step")
        ax.set_ylim(-0.03, 1.03)
        ax.grid(alpha=0.3)
        ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT / "s1_true_and_hardcoding.png", dpi=130)
    plt.close(fig)
    (UWU / "tables.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
