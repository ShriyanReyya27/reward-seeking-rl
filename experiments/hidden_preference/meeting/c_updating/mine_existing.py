"""Mine existing hidden_preference k-sweeps for how fast each arm moves with evidence, truncation handled.

    uv run --with numpy python experiments/hidden_preference/meeting/c_updating/mine_existing.py

Reads results/{pilot,discovery_v1,discovery_persist,discovery_persist_time}/samples.jsonl. For each run reports
accuracy by k and arm on finished samples only and on all samples (unfinished count as misses), the gain from k=0,
and per-rule breakdowns (discovery runs; pilot rule fields too). 95% bootstrap CIs resample requests (base_id).
Output: mined_k_sweeps.md, next to this script.
"""
from __future__ import annotations
import json
from collections import defaultdict
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parents[1] / "results"
ARMS = ("c430", "oss430")
RNG = np.random.default_rng(0)
B = 2000


def load(run):
    return [json.loads(l) for l in (RESULTS / run / "samples.jsonl").read_text().splitlines() if l.strip()]


def boot_cell(by_req):
    """mean and 95% CI of per-request reward, resampling requests. by_req: {base_id: [0/1,...]}."""
    means = np.array([np.mean(v) for v in by_req.values()], float)
    if len(means) == 0:
        return float("nan"), float("nan"), float("nan")
    idx = RNG.integers(0, len(means), (B, len(means)))
    bs = means[idx].mean(1)
    return 100 * means.mean(), 100 * np.percentile(bs, 2.5), 100 * np.percentile(bs, 97.5)


def fmt(t):
    return f"{t[0]:.0f} [{t[1]:.0f}, {t[2]:.0f}]"


def cell(rows, finished_only):
    by = defaultdict(list)
    for r in rows:
        if finished_only and not r["finished"]:
            continue
        by[r["base_id"]].append(float(r["reward"] > 0))
    return by


def gain_diff(rows, ks, finished_only):
    """oss430 - c430 mean gain over k>0 vs k=0, paired by base_id, bootstrap over base_ids.
    Each request's gain = mean(reward at k in ks) - mean(reward at k=0) for that request and arm (no k=0 weighting
    beyond the request-level mean)."""
    tab = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))  # base_id -> arm -> k -> [rew]
    for r in rows:
        if finished_only and not r["finished"]:
            continue
        tab[r["base_id"]][r["arm"]][r["k"]].append(float(r["reward"] > 0))
    ids = [b for b in tab if all(tab[b][a].get(0) and any(tab[b][a].get(k) for k in ks) for a in ARMS)]
    if not ids:
        return (float("nan"),) * 3, 0
    def d(b):
        out = {}
        for a in ARMS:
            g0 = np.mean(tab[b][a][0])
            gk = np.mean([x for k in ks for x in tab[b][a].get(k, [])])
            out[a] = gk - g0
        return out["oss430"] - out["c430"]
    ds = np.array([d(b) for b in ids])
    idx = RNG.integers(0, len(ds), (B, len(ds)))
    bs = ds[idx].mean(1)
    return (100 * ds.mean(), 100 * np.percentile(bs, 2.5), 100 * np.percentile(bs, 97.5)), len(ids)


def table_by_k(rows, ks, key_fn, key_label, min_n=0):
    """Accuracy per (key, k, arm): finished-only with CI, and all-sample (unfinished=miss) in parentheses."""
    cells = defaultdict(list)
    for r in rows:
        cells[(key_fn(r), r["k"], r["arm"])].append(r)
    keys = sorted({c[0] for c in cells}, key=str)
    out = [f"| {key_label} | arm | " + " | ".join(f"k={k}" for k in ks) + " | gain k_max-k0 (finished) | unfinished % |",
           "|---" * (len(ks) + 4) + "|"]
    for key in keys:
        for a in ARMS:
            vals = []
            unf = [r for k in ks for r in cells.get((key, k, a), []) if not r["finished"]]
            nall = sum(len(cells.get((key, k, a), [])) for k in ks)
            for k in ks:
                xs = cells.get((key, k, a), [])
                if not xs:
                    vals.append("-")
                    continue
                f = boot_cell(cell(xs, True))
                nf = sum(1 for r in xs if r["finished"])
                raw = 100 * np.mean([r["reward"] > 0 for r in xs])
                vals.append(f"{f[0]:.0f} [{f[1]:.0f},{f[2]:.0f}] (all {raw:.0f}, n={nf})")
            k0 = cells.get((key, 0, a), [])
            kmax = cells.get((key, ks[-1], a), [])
            g = np.nan
            if k0 and kmax:
                f0 = [r["reward"] > 0 for r in k0 if r["finished"]]
                fk = [r["reward"] > 0 for r in kmax if r["finished"]]
                if f0 and fk:
                    g = 100 * (np.mean(fk) - np.mean(f0))
            out.append(f"| {key} | {a} | " + " | ".join(vals) + f" | {g:+.0f} | {100*len(unf)/max(1,nall):.1f} |")
    return "\n".join(out)


def main():
    md = ["# Existing k-sweeps, mined", "", "Accuracy = reward > 0 (valid and meets the hidden rule). Finished samples "
          "only unless stated; '(all N)' counts unfinished as misses. 95% bootstrap CIs over requests (base_id). "
          "Generated by mine_existing.py.", ""]
    p = [r for r in load("pilot") if r["arm"] in ARMS]
    md += ["## pilot (rule random per episode, k in {0,2,4,6}, 32 episodes per family and mix; max_tokens 3000)", ""]
    for framing in ("plain", "explicit"):
        rows = [r for r in p if r["framing"] == framing]
        md += [f"### framing = {framing}", "", table_by_k(rows, [0, 2, 4, 6], lambda r: r["family"], "family"), ""]
        for fin in (True, False):
            g, n = gain_diff(rows, [2, 4, 6], fin)
            md.append(f"oss430-c430 gain from k=0 to k>0, {'finished only' if fin else 'all samples'}, all families: "
                      f"{g[0]:+.1f} pp [{g[1]:+.1f}, {g[2]:+.1f}] (n={n} requests).")
        for fam in ("number", "word", "format", "tagline"):
            fr = [r for r in rows if r["family"] == fam]
            g, n = gain_diff(fr, [2, 4, 6], True)
            md.append(f"  {fam}: {g[0]:+.1f} pp [{g[1]:+.1f}, {g[2]:+.1f}] (n={n}).")
        md.append("")
        md += ["Per-rule (framing=" + framing + "; rule resampled per episode, so few per cell, finished only):", "",
               table_by_k(rows, [0, 2, 4, 6], lambda r: f"{r['family']}:{r['rule']}", "family:rule"), ""]
    for run in ("discovery_v1", "discovery_persist", "discovery_persist_time"):
        rows = [r for r in load(run) if r["arm"] in ARMS]
        md += [f"## {run} (explicit framing, nested histories k in {{0,2,4,8,12}}, 16 episodes per rule and k; 8k tokens)", ""]
        md += ["### by tier", "", table_by_k(rows, [0, 2, 4, 8, 12], lambda r: f"{r['family']}:{r['tier']}", "family:tier"), ""]
        for tier in ("easy", "medium", "hard", None):
            tr = [r for r in rows if tier is None or r["tier"] == tier]
            g, n = gain_diff(tr, [2, 4, 8, 12], True)
            g2, _ = gain_diff(tr, [2, 4, 8, 12], False)
            md.append(f"gain oss430-c430, tier={tier or 'all'}: finished {g[0]:+.1f} [{g[1]:+.1f}, {g[2]:+.1f}] (n={n}); "
                      f"all samples {g2[0]:+.1f} [{g2[1]:+.1f}, {g2[2]:+.1f}].")
        md += ["", "### per rule, with matched-k0 flag (finished only)", ""]
        tab = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))
        for r in rows:
            tab[(r["family"], r["rule"])][r["k"]][r["arm"]].append(r)
        out = ["| family:rule | tier | arm | k=0 | k=2 | k=4 | k=8 | k=12 | k0 matched (|diff|<=5pp, finished) |", "|" + "---|" * 9]
        for (fam, rule), byk in sorted(tab.items()):
            k0 = {a: [r["reward"] > 0 for r in byk[0][a] if r["finished"]] for a in ARMS}
            rates0 = {a: (100 * np.mean(k0[a]) if k0[a] else float("nan")) for a in ARMS}
            match = abs(rates0["oss430"] - rates0["c430"]) <= 5
            tier = next(r["tier"] for arm in ARMS for r in byk[0][arm])
            for a in ARMS:
                vals = []
                for k in (0, 2, 4, 8, 12):
                    xs = [r for r in byk.get(k, {}).get(a, []) if r["finished"]]
                    vals.append(f"{100*np.mean([r['reward']>0 for r in xs]):.0f} ({len(xs)})" if xs else "-")
                out.append(f"| {fam}:{rule} | {tier} | {a} | " + " | ".join(vals) + f" | {'yes' if match else 'no'} ({rates0['c430']:.0f} vs {rates0['oss430']:.0f}) |")
        md += ["\n".join(out), ""]
    (HERE / "mined_k_sweeps.md").write_text("\n".join(md) + "\n")
    print("\n".join(md)[:6000])


if __name__ == "__main__":
    main()
